#!/usr/bin/env node
// Reads config/servers.yaml (and decrypts config/secrets/ via sops if available)
// and writes infra/ansible/inventory/group_vars/<server>.yml for each server.
// If SOPS_AGE_KEY is not available, writes placeholder values.
//
// Usage: node scripts/generate-ansible-inventory.js

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { execSync } from "child_process";
import yaml from "js-yaml";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const servers = yaml.load(readFileSync(resolve(root, "config/servers.yaml"), "utf8"));

// ── Secrets decryption ─────────────────────────────────────────────
let secrets = null;

if (process.env.SOPS_AGE_KEY || process.env.SOPS_AGE_KEY_FILE) {
  const serversEncPath = resolve(root, "config/secrets/servers.enc.yaml");
  if (existsSync(serversEncPath)) {
    try {
      const out = execSync(`sops --decrypt "${serversEncPath}"`, {
        encoding: "utf8",
        env: { ...process.env },
        stdio: ["pipe", "pipe", "pipe"],
      });
      secrets = yaml.load(out);
      console.log("✓ Decrypted config/secrets/servers.enc.yaml");
    } catch (e) {
      console.warn(`⚠ sops decrypt failed: ${e.message.split("\n")[0]}`);
    }
  }
} else {
  console.log("ℹ No SOPS_AGE_KEY set — using placeholder values");
}

// ── Tag → group_vars filename mapping ─────────────────────────────
const TAG_TO_FILENAME = {
  helsinki: "helsinki",
  "oracle-madrid": "oracle",
  "gcp-middle-east": "gcp",
  "scaleway-london": "scaleway",
};

const outDir = resolve(root, "infra/ansible/inventory/group_vars");
mkdirSync(outDir, { recursive: true });

for (const server of servers.servers) {
  const filename = TAG_TO_FILENAME[server.tag];
  if (!filename) {
    console.warn(`⚠ Unknown server tag: ${server.tag} — skipping`);
    continue;
  }

  const ip = process.env[server.ip_env] || secrets?.[server.ip_env] || `<${server.ip_env}>`;
  const ipv6 = server.ipv6_env
    ? (process.env[server.ipv6_env] || secrets?.[server.ipv6_env] || null)
    : null;

  const vars = {
    server_ip: ip,
    server_ipv6: ipv6,
    server_tag: server.tag,
    server_location: server.location,
    server_provider: server.provider,
    has_naiveproxy: !!server.naive,
    has_cloak: !!server.cloak,
    has_shadowtls: false,
    has_finalmask: false,
    has_dnstt: server.has_dns_tunnel || false,
    has_amneziawg: !!server.amneziawg,
  };

  const content = [
    "---",
    `# Auto-generated by scripts/generate-ansible-inventory.js`,
    `# Source: config/servers.yaml tag=${server.tag}`,
    yaml.dump(vars, { lineWidth: 120 }).trim(),
  ].join("\n") + "\n";

  const outPath = resolve(outDir, `${filename}.yml`);
  writeFileSync(outPath, content);
  console.log(`✓ Written: infra/ansible/inventory/group_vars/${filename}.yml`);
}

console.log("✓ Ansible inventory group_vars generated");
