#!/usr/bin/env node
// Reads config/servers.yaml and decrypts config/secrets/ (via sops if available)
// and writes infra/terraform/environments/production/terraform.tfvars (gitignored).
//
// Usage: node scripts/generate-terraform-vars.js

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { execSync } from "child_process";
import yaml from "js-yaml";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const servers = yaml.load(readFileSync(resolve(root, "config/servers.yaml"), "utf8"));

let secrets = null;
if (process.env.SOPS_AGE_KEY || process.env.SOPS_AGE_KEY_FILE) {
  const serversEncPath = resolve(root, "config/secrets/servers.enc.yaml");
  if (existsSync(serversEncPath)) {
    try {
      const out = execSync(`sops --decrypt "${serversEncPath}"`, {
        encoding: "utf8",
        env: { ...process.env },
        stdio: ["pipe", "pipe", "pipe"],
      });
      secrets = yaml.load(out);
      console.log("✓ Decrypted config/secrets/servers.enc.yaml");
    } catch (e) {
      console.warn(`⚠ sops decrypt failed: ${e.message.split("\n")[0]}`);
    }
  }
} else {
  console.log("ℹ No SOPS_AGE_KEY set — writing placeholder values to terraform.tfvars");
  console.warn("⚠ Generated terraform.tfvars contains placeholders — set env vars or SOPS key for real values");
}

function getVal(envKey) {
  return process.env[envKey] || secrets?.[envKey] || `<${envKey}>`;
}

const lines = [
  `# Auto-generated by scripts/generate-terraform-vars.js — DO NOT COMMIT`,
  `# Generated at ${new Date().toISOString()}`,
  ``,
  `hetzner_ssh_public_key     = "${getVal("HEL_SSH_PUBKEY")}"`,
  `hetzner_token              = "${getVal("HETZNER_TOKEN")}"`,
  ``,
  `oracle_compartment_id      = "${getVal("OCI_COMPARTMENT_ID")}"`,
  `oracle_availability_domain = "${getVal("OCI_AVAILABILITY_DOMAIN")}"`,
  `oracle_ssh_public_key      = "${getVal("ORC_SSH_PUBKEY")}"`,
  ``,
  `gcp_project_id             = "${getVal("GCP_PROJECT_ID")}"`,
  `gcp_ssh_public_key         = "${getVal("GCP_SSH_PUBKEY")}"`,
  ``,
  `scaleway_ssh_public_key    = "${getVal("SCW_SSH_PUBKEY")}"`,
  ``,
  `cloudflare_zone_id         = "${getVal("CF_ZONE_ID")}"`,
  `cloudflare_account_id      = "${getVal("CF_ACCOUNT_ID")}"`,
  `cloudflare_api_token       = "${getVal("CF_API_TOKEN")}"`,
];

const outPath = resolve(root, "infra/terraform/environments/production/terraform.tfvars");
mkdirSync(resolve(root, "infra/terraform/environments/production"), { recursive: true });
writeFileSync(outPath, lines.join("\n") + "\n");
console.log("✓ infra/terraform/environments/production/terraform.tfvars written");
